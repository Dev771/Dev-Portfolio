export type IconName = keyof typeof ICONS;

interface Props {
  name: IconName;
  /** size of one icon pixel in CSS pixels */
  px?: number;
  className?: string;
  color?: string;
}

export default function PixelIcon({ name, px = 3, className, color = "currentColor" }: Props) {
  const rows = ICONS[name];
  const w = rows[0].length;
  const h = rows.length;
  return (
    <svg
      className={className}
      width={w * px}
      height={h * px}
      viewBox={`0 0 ${w} ${h}`}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      fill={color}
    >
      {rows.flatMap((row, y) =>
        [...row].map((ch, x) => (ch === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} /> : null)),
      )}
    </svg>
  );
}
